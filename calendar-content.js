const CALENDAR_ZONE='Asia/Riyadh';
const DAY_MS=86400000;
function calendarDay(date){
 const parts=new Intl.DateTimeFormat('en-CA',{timeZone:CALENDAR_ZONE,year:'numeric',month:'2-digit',day:'2-digit'}).formatToParts(date);
 const part=type=>Number(parts.find(p=>p.type===type).value);
 return Math.floor(Date.UTC(part('year'),part('month')-1,part('day'))/DAY_MS);
}
function isFriday(date){return new Date(calendarDay(date)*DAY_MS).getUTCDay()===5}
function isNationalDay(date){const day=new Date(calendarDay(date)*DAY_MS);return day.getUTCMonth()===8&&day.getUTCDate()===23}
function messagePool(date){return isFriday(date)?FRIDAY_MESSAGES:isNationalDay(date)?NATIONAL_DAY_MESSAGES:DAILY_MESSAGES}
function messageFor(date,offset=0){
 const friday=isFriday(date),national=isNationalDay(date),pool=messagePool(date);
 const sequence=friday?Math.floor(calendarDay(date)/7):national?0:calendarDay(date);
 return {label:friday?'رسالة الجمعة':national?'رسالة اليوم الوطني':'رسالة اليوم',text:pool[((sequence+offset)%pool.length+pool.length)%pool.length]};
}
const occasionCache=new Map();
function upcomingOccasion(date){
 const day=calendarDay(date);if(occasionCache.has(day))return occasionCache.get(day);
 const hijriParts=new Intl.DateTimeFormat('en-US-u-ca-islamic-umalqura',{timeZone:'UTC',month:'numeric',day:'numeric'});
 let result=null;
 // Only show an occasion within the next fourteen calendar days, including today.
 for(let remaining=0;remaining<=14;remaining++){
  const d=new Date((day+remaining)*DAY_MS),parts=hijriParts.formatToParts(d);
  const month=Number(parts.find(p=>p.type==='month').value),dom=Number(parts.find(p=>p.type==='day').value);
  let name='',estimated=false;
  if(d.getUTCMonth()===8&&d.getUTCDate()===23)name='اليوم الوطني السعودي';
  else if(month===9&&dom===1){name='شهر رمضان';estimated=true}
  else if(month===10&&dom===1){name='عيد الفطر';estimated=true}
  else if(month===12&&dom===10){name='عيد الأضحى';estimated=true}
  if(name){result={name,remaining,estimated};break}
 }
 if(occasionCache.size>32)occasionCache.clear();occasionCache.set(day,result);return result;
}
function occasionCountdown(event){
 if(event.remaining===0)return 'اليوم';
 if(event.remaining===1)return 'متبقي يوم واحد';
 if(event.remaining===2)return 'متبقي يومان';
 return 'متبقي '+new Intl.NumberFormat('ar-SA').format(event.remaining)+(event.remaining<=10?' أيام':' يومًا');
}
